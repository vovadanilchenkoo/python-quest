export type Kind = "choice" | "type" | "gaps" | "bug" | "order";

export interface ChoiceOption {
  text: string;
  correct?: boolean;
  why: string; // пояснення саме для цього варіанта
}

export interface Gap {
  id: string;
  options: string[];
  correct: string;
  why: string;
}

export interface Mission {
  id: string;
  level: number;
  kind: Kind;
  title: string;
  skill: string; // що відпрацьовується
  story: string;
  question: string;
  code?: string; // для choice / type / bug (рядки), для gaps — шаблон з [[id]]
  options?: ChoiceOption[];
  answers?: string[]; // для type
  typeWhy?: string;
  gaps?: Gap[];
  bugLines?: number[]; // правильні рядки
  bugWhy?: string;
  bugAlt?: string; // коментар, якщо обрано альтернативний рядок
  orderLines?: string[]; // правильний порядок
  orderWhy?: string;
  hints: string[];
  explain: string;
}

export interface Level {
  id: number;
  title: string;
  role: string;
  topic: string;
  story: string;
  required: number; // скільки місій треба пройти, щоб відкрити наступний рівень
}

